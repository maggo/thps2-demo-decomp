#!/usr/bin/env python3
"""Generate src/SQRTTAB.inc, the initializer of SqrtTable in src/SQRTTAB.cpp.

Entry i is floor(1024 * sqrt(i + 1024.5)) for i in 0..3071: ten-bit fixed-point
square roots of the inputs 1024.5 through 4095.5, computed exactly with integer
arithmetic as isqrt((2 * i + 2049) * 2**19).

    python3 tools/generate_sqrttab.py            # rewrite src/SQRTTAB.inc
    python3 tools/generate_sqrttab.py --check    # fail if the file differs
"""
import math
import sys
from pathlib import Path

COUNT = 3072
PER_LINE = 8
OUT = Path(__file__).resolve().parent.parent / 'src' / 'SQRTTAB.inc'


def render():
    values = [math.isqrt((2 * i + 2049) << 19) for i in range(COUNT)]
    lines = ['/* Generated by tools/generate_sqrttab.py; do not edit manually. */']
    for k in range(0, COUNT, PER_LINE):
        lines.append('    ' + ', '.join(str(v) for v in values[k:k + PER_LINE]) + ',')
    return '\n'.join(lines) + '\n'


def main():
    text = render()
    if '--check' in sys.argv[1:]:
        if OUT.read_text() != text:
            sys.exit(f'{OUT} differs from the generator output')
        print(f'{OUT.name}: up to date')
        return
    OUT.write_text(text)


if __name__ == '__main__':
    main()
